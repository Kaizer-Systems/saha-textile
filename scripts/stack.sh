#!/usr/bin/env bash
# =============================================================================
#  Mode 3 helper — the full local stack (docker/stack/compose.yaml)
#
#    scripts/stack.sh certs    issue certs/stack-*.pem for the three stack hosts (mkcert)
#    scripts/stack.sh env      write docker/stack/env/*.env + *.config.json (gitignored)
#    scripts/stack.sh up       build images, start, wait until healthy
#    scripts/stack.sh down     stop (volumes kept)
#    scripts/stack.sh logs [service]
#    scripts/stack.sh status
#
#  Secrets are copied from apps/api/.env into docker/stack/env/api.env, which is
#  gitignored and docker-ignored: they reach containers at runtime, never an image.
# =============================================================================
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
STACK_DIR="$ROOT_DIR/docker/stack"
ENV_DIR="$STACK_DIR/env"
CERT_DIR="$ROOT_DIR/certs"
COMPOSE=(docker compose -f "$STACK_DIR/compose.yaml")

# The edge's host port: 443 unless env/stack.env says otherwise (some machines already use 443).
if [[ -f "$ENV_DIR/stack.env" ]]; then
	STACK_HTTPS_PORT="$(sed -n 's/^STACK_HTTPS_PORT=//p' "$ENV_DIR/stack.env")"
fi
export STACK_HTTPS_PORT="${STACK_HTTPS_PORT:-443}"
PORT_SUFFIX=""
[[ "$STACK_HTTPS_PORT" == "443" ]] || PORT_SUFFIX=":$STACK_HTTPS_PORT"

STOREFRONT_HOST="local.saha-textile.localhost"
ADMIN_HOST="admin-local.saha-textile.localhost"
API_HOST="api-local.saha-textile.localhost"

cmd_certs() {
	command -v mkcert >/dev/null 2>&1 || { echo "mkcert is not installed (brew install mkcert nss)" >&2; exit 1; }
	mkcert -install
	mkdir -p "$CERT_DIR"
	mkcert -cert-file "$CERT_DIR/stack-cert.pem" -key-file "$CERT_DIR/stack-key.pem" \
		"$STOREFRONT_HOST" "$ADMIN_HOST" "$API_HOST"
	chmod 600 "$CERT_DIR/stack-key.pem"
	# The CA's PUBLIC certificate, so SSR inside a container trusts the edge. Never the CA key.
	cp "$(mkcert -CAROOT)/rootCA.pem" "$CERT_DIR/rootCA.pem"
	echo "Stack certificate issued for $STOREFRONT_HOST, $ADMIN_HOST, $API_HOST"
}

# Keys from apps/api/.env that the stack sets itself.
OVERRIDDEN='^(NODE_ENV|DEPLOY_ENV|PORT|CORS_ALLOWED_ORIGINS|TRUST_PROXY|CLIENT_IP_HEADER|MONGODB_[A-Z_]+|REDIS_[A-Z_]+|MEILISEARCH_HOST|COOKIE_DOMAIN|COOKIE_SECURE|TLS_CERT_FILE|TLS_KEY_FILE|OTP_LOCAL_FIXED_CODE)='

cmd_env() {
	local source="$ROOT_DIR/apps/api/.env"
	[[ -f "$source" ]] || { echo "apps/api/.env is missing — create it first (see apps/api/.env.example)" >&2; exit 1; }
	mkdir -p "$ENV_DIR"

	if [[ ! -f "$ENV_DIR/stack.env" ]]; then
		printf 'REDIS_PASSWORD=%s\n' "$(openssl rand -hex 24)" >"$ENV_DIR/stack.env"
	fi

	{
		echo "# Generated by scripts/stack.sh env from apps/api/.env — gitignored, never commit."
		grep -Ev "$OVERRIDDEN" "$source" | grep -Ev '^\s*(#|$)'
		cat <<VARS
NODE_ENV=production
DEPLOY_ENV=local
PORT=4000
MONGODB_HOST=mongo
MONGODB_PORT=27017
MONGODB_REPLICA_SET=rs0
MONGODB_DB_NAME=saha_textile_stack
REDIS_HOST=redis
REDIS_PORT=6379
MEILISEARCH_HOST=http://meilisearch:7700
CORS_ALLOWED_ORIGINS=https://$STOREFRONT_HOST$PORT_SUFFIX,https://$ADMIN_HOST$PORT_SUFFIX
TRUST_PROXY=true
CLIENT_IP_HEADER=cf-connecting-ip
COOKIE_SECURE=true
VARS
	} >"$ENV_DIR/api.env"
	chmod 600 "$ENV_DIR/api.env" "$ENV_DIR/stack.env"

	local google facebook
	google="$(sed -n 's/^GOOGLE_OAUTH_CLIENT_ID=//p' "$source")"
	facebook="$(sed -n 's/^FACEBOOK_OAUTH_APP_ID=//p' "$source")"
	local public_config
	public_config=$(cat <<JSON
{
	"apiUrl": "https://$API_HOST$PORT_SUFFIX",
	"siteUrl": "https://$STOREFRONT_HOST$PORT_SUFFIX",
	"defaultLocale": "en",
	"supportedLocales": ["en", "fr"],
	"googleClientId": "$google",
	"facebookAppId": "$facebook"
}
JSON
)
	echo "$public_config" >"$ENV_DIR/storefront.config.json"
	{
		echo "# Generated by scripts/stack.sh env — public, non-secret runtime config."
		echo "SAHA_TEXTILE_PUBLIC_CONFIG=$(echo "$public_config" | tr -d '\n\t')"
		echo "NODE_EXTRA_CA_CERTS=/certs/rootCA.pem"
	} >"$ENV_DIR/storefront.env"
	printf '{\n\t"apiUrl": "https://%s",\n\t"adminUrl": "https://%s"\n}\n' "$API_HOST$PORT_SUFFIX" "$ADMIN_HOST$PORT_SUFFIX" >"$ENV_DIR/admin.config.json"

	echo "Wrote docker/stack/env (api.env, stack.env, storefront.env, *.config.json)."
	echo "Safari only — add to /etc/hosts:  127.0.0.1 $STOREFRONT_HOST $ADMIN_HOST $API_HOST"
}

cmd_up() {
	[[ -f "$CERT_DIR/stack-cert.pem" ]] || { echo "Run: pnpm stack:certs" >&2; exit 1; }
	[[ -f "$ENV_DIR/api.env" ]] || { echo "Run: pnpm stack:env" >&2; exit 1; }
	"${COMPOSE[@]}" up -d --build --wait
	# A broken config.json does not stop the app: the browser silently falls back to localhost.
	curl -fsk "https://$STOREFRONT_HOST$PORT_SUFFIX/config.json" |
		node -e 'JSON.parse(require("fs").readFileSync(0, "utf8"))' ||
		{ echo "The storefront is not serving a valid config.json." >&2; exit 1; }
	echo
	echo "  storefront  https://$STOREFRONT_HOST$PORT_SUFFIX"
	echo "  admin       https://$ADMIN_HOST$PORT_SUFFIX"
	echo "  API         https://$API_HOST$PORT_SUFFIX/health/ready"
}

case "${1:-}" in
	certs) cmd_certs ;;
	env) cmd_env ;;
	up) cmd_up ;;
	down) "${COMPOSE[@]}" down ;;
	logs) shift; "${COMPOSE[@]}" logs -f --tail=200 "$@" ;;
	status) "${COMPOSE[@]}" ps ;;
	*) sed -n '2,14p' "$0"; exit 1 ;;
esac
